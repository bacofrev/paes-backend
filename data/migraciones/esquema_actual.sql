--
-- Name: v_active_misconceptions; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_active_misconceptions AS
 SELECT r.student_id,
    m.code AS misconception_code,
    m.name AS misconception_name,
    count(*) AS occurrences,
    count(DISTINCT r.item_id) AS distinct_items,
    count(DISTINCT ni.node_id) AS distinct_nodes,
    max(r.created_at) AS last_seen
   FROM (((public.responses r
     JOIN public.item_options o ON ((o.id = r.option_id)))
     JOIN public.misconceptions m ON ((m.id = o.misconception_id)))
     LEFT JOIN public.node_items ni ON ((ni.item_id = r.item_id)))
  WHERE (r.created_at > (now() - '30 days'::interval))
  GROUP BY r.student_id, m.code, m.name
 HAVING (count(DISTINCT r.item_id) >= 3);


--
-- Name: v_node_mastery; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_node_mastery AS
 SELECT nm.student_id,
    n.code AS node_code,
    n.name AS node_name,
    a.code AS area_code,
    nm.p_correct,
    nm.items_answered,
    nm.items_correct,
    nm.hard_correct,
    nm.status,
        CASE
            WHEN ((nm.status = 'mastered'::text) AND (nm.last_response_at < (now() - ((cfg.validity_days || ' days'::text))::interval))) THEN 'lapsed'::text
            ELSE nm.status
        END AS effective_status,
    nm.last_response_at,
    nm.first_mastered_at,
    nm.config_version,
    nm.computed_at
   FROM (((public.node_mastery nm
     JOIN public.nodes n ON ((n.id = nm.node_id)))
     JOIN public.areas a ON ((a.id = n.area_id)))
     CROSS JOIN LATERAL ( SELECT mastery_config.validity_days
           FROM public.mastery_config
          WHERE (mastery_config.version = nm.config_version)) cfg);


--
-- Name: v_available_nodes; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_available_nodes AS
 SELECT st.id AS student_id,
    n.id AS node_id,
    n.code,
    n.name,
    u.code AS unit_code,
    n.exam_level,
    COALESCE(vm.effective_status, 'not_started'::text) AS status,
    count(*) FILTER (WHERE ((pre.status <> 'rejected'::text) AND (COALESCE(pm.effective_status, 'not_started'::text) <> 'mastered'::text))) AS pending_prereqs
   FROM (((((((public.students st
     CROSS JOIN public.nodes n)
     JOIN public.units u ON ((u.id = n.unit_id)))
     JOIN public.areas ar ON ((ar.id = n.area_id)))
     LEFT JOIN public.v_node_mastery vm ON (((vm.student_id = st.id) AND ((vm.node_code)::text = (n.code)::text))))
     LEFT JOIN public.node_edges pre ON ((pre.target_id = n.id)))
     LEFT JOIN public.nodes prn ON ((prn.id = pre.prereq_id)))
     LEFT JOIN public.v_node_mastery pm ON (((pm.student_id = st.id) AND ((pm.node_code)::text = (prn.code)::text))))
  WHERE ((n.status = 'active'::text) AND (EXISTS ( SELECT 1
           FROM (public.student_courses sc
             JOIN public.courses c ON ((c.id = sc.course_id)))
          WHERE ((sc.student_id = st.id) AND (sc.status = 'active'::text) AND (c.status = 'active'::text) AND (c.subject_id = ar.subject_id) AND ((c.area_id IS NULL) OR (c.area_id = n.area_id)) AND (n.exam_level <= c.exam_level)))))
  GROUP BY st.id, n.id, n.code, n.name, u.code, n.exam_level, vm.effective_status;


